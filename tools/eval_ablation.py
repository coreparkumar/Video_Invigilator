"""Ablation harness: video-only vs audio-only vs fused comparison.

Input CSV columns: session, t, truth, audio_event, video_cue (0/1 each)
Output: markdown table with per-detector and overall metrics.
"""
import argparse
import csv
import sys
from pathlib import Path
import numpy as np


def compute_metrics(tp, fp, fn, total_seconds):
    """Compute precision, recall, F1, false alarms per hour."""
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0
    fa_per_hour = fp / (total_seconds / 3600) if total_seconds > 0 else 0.0
    return {
        "tp": tp, "fp": fp, "fn": fn,
        "precision": precision, "recall": recall, "f1": f1,
        "fa_per_hour": fa_per_hour
    }


def main():
    ap = argparse.ArgumentParser(description="Ablation: video-only vs audio-only vs fused")
    ap.add_argument("sessions_csv", help="CSV with columns: session,t,truth,audio_event,video_cue")
    ap.add_argument("--out", default="docs/ABLATION.md", help="Output markdown file")
    args = ap.parse_args()

    csv_path = Path(args.sessions_csv)
    if not csv_path.exists():
        print(f"Error: {csv_path} not found")
        sys.exit(1)

    # Read data
    sessions = {}
    with open(csv_path, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            session = row["session"]
            if session not in sessions:
                sessions[session] = {"t": [], "truth": [], "audio": [], "video": []}
            sessions[session]["t"].append(float(row["t"]))
            sessions[session]["truth"].append(int(row["truth"]))
            sessions[session]["audio"].append(int(row["audio_event"]))
            sessions[session]["video"].append(int(row["video_cue"]))

    # Warn if too few sessions or truth seconds
    if len(sessions) < 3:
        print(f"WARNING: Only {len(sessions)} sessions (< 3 recommended)")
    total_truth = sum(sum(s["truth"]) for s in sessions.values())
    if total_truth < 20:
        print(f"WARNING: Only {total_truth} truth seconds (< 20 recommended)")

    # Compute per-detector metrics per session
    modalities = ["video", "audio", "fused"]
    results = {m: {} for m in modalities}

    for session_name, data in sessions.items():
        t = np.array(data["t"])
        truth = np.array(data["truth"])
        audio = np.array(data["audio"])
        video = np.array(data["video"])

        total_seconds = t[-1] - t[0] if len(t) > 1 else 1.0

        # Video-only
        tp = np.sum((video == 1) & (truth == 1))
        fp = np.sum((video == 1) & (truth == 0))
        fn = np.sum((video == 0) & (truth == 1))
        results["video"][session_name] = compute_metrics(tp, fp, fn, total_seconds)

        # Audio-only
        tp = np.sum((audio == 1) & (truth == 1))
        fp = np.sum((audio == 1) & (truth == 0))
        fn = np.sum((audio == 0) & (truth == 1))
        results["audio"][session_name] = compute_metrics(tp, fp, fn, total_seconds)

        # Fused: audio event within AUDIO_HOLD_S AND video cue now
        # Simplified: fused = audio AND video at same timestep
        fused = (audio == 1) & (video == 1)
        tp = np.sum((fused == 1) & (truth == 1))
        fp = np.sum((fused == 1) & (truth == 0))
        fn = np.sum((fused == 0) & (truth == 1))
        results["fused"][session_name] = compute_metrics(tp, fp, fn, total_seconds)

    # Aggregate across sessions
    def aggregate(mod_results):
        total_tp = sum(r["tp"] for r in mod_results.values())
        total_fp = sum(r["fp"] for r in mod_results.values())
        total_fn = sum(r["fn"] for r in mod_results.values())
        total_sec = sum(
            sessions[s]["t"][-1] - sessions[s]["t"][0] if len(sessions[s]["t"]) > 1 else 1.0
            for s in mod_results
        )
        return compute_metrics(total_tp, total_fp, total_fn, total_sec)

    agg = {m: aggregate(results[m]) for m in modalities}

    # Print markdown table
    out_path = Path("docs/ABLATION.md")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    with open(out_path, "w") as f:
        f.write("# Ablation Study: Video-only vs Audio-only vs Fused\n\n")
        f.write("> Generated by `tools/eval_ablation.py`. Fill in after running ablation evaluation.\n\n")

        # Per-session
        f.write("## Per-Session Results\n\n")
        f.write("| Session | Modality | TP | FP | FN | Precision | Recall | F1 | FA/hr |\n")
        f.write("|---------|----------|----|----|----|-----------|--------|----|-------|\n")
        for mod in modalities:
            for session_name, m in results[mod].items():
                f.write(f"| {session_name} | {mod} | {m['tp']} | {m['fp']} | {m['fn']} | "
                        f"{m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | {m['fa_per_hour']:.2f} |\n")

        # Aggregate
        f.write("\n## Aggregate Results\n\n")
        f.write("| Modality | Precision | Recall | F1 | False Alarms/hr |\n")
        f.write("|----------|-----------|--------|----|-----------------|\n")
        for mod in modalities:
            m = agg[mod]
            f.write(f"| {mod} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | {m['fa_per_hour']:.2f} |\n")

        f.write("\n## Analysis\n\n")
        f.write("- Does audio add value over video alone? _\n")
        f.write("- Does fusion reduce false alarms compared to either alone? _\n")
        f.write("- What are the main failure modes? _\n")
        f.write("- Distance/noise conditions where audio helps/hurts? _\n\n")

        f.write("## Notes\n\n")
        f.write("- Generated by `tools/eval_ablation.py sessions.csv`\n")
        f.write("- Data source: _\n")
        f.write("- Thresholds used: (from audio/config.py and invigilator/config.py)\n")
        f.write("- **Caution:** Do not tune thresholds on this same data!\n")

    print(f"Results written to {out_path}")

    # Print summary to console
    print("\nAblation Summary:")
    print(f"{'Modality':<10} {'Prec':>6} {'Rec':>6} {'F1':>6} {'FA/hr':>8}")
    for mod in modalities:
        m = agg[mod]
        print(f"{mod:<10} {m['precision']:.3f}   {m['recall']:.3f}   {m['f1']:.3f}   {m['fa_per_hour']:.2f}")


if __name__ == "__main__":
    main()